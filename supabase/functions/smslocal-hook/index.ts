import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const SMSLOCAL_API_KEY = Deno.env.get("SMSLOCAL_API_KEY") ?? "4ef21cfb871fd16eda815642b8e4cca0";
const SMSLOCAL_TEMPLATE_ID = Deno.env.get("SMSLOCAL_TEMPLATE_ID") ?? "";
const SMSLOCAL_SENDER_ID = Deno.env.get("SMSLOCAL_SENDER_ID") ?? "";

serve(async (req: Request) => {
  // Handle CORS preflight
  if (req.method === "OPTIONS") {
    return new Response("ok", {
      headers: {
        "Access-Control-Allow-Origin": "*",
        "Access-Control-Allow-Methods": "POST, OPTIONS",
        "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
      },
    });
  }

  try {
    const payload = await req.json();
    console.log("Supabase SMS Hook triggered with payload:", JSON.stringify(payload));

    const rawPhone = payload?.user?.phone ?? ""; // E.g. "+919876543210"
    const otpCode = payload?.sms?.otp ?? "";     // 6-digit OTP generated by Supabase

    if (!rawPhone || !otpCode) {
      return new Response(
        JSON.stringify({ error: "Missing phone number or OTP code" }),
        { status: 400, headers: { "Content-Type": "application/json" } }
      );
    }

    // Clean phone number (e.g. remove leading '+' or country code if needed)
    const cleanNumber = rawPhone.replace(/^\+91/, "").replace(/\D/g, "");
    const message = `Your FoodFlow verification OTP is ${otpCode}. Valid for 5 minutes. Do not share.`;

    // Construct SMSLocal API request URL
    const url = new URL("https://app.smslocal.in/api/smsapi");
    url.searchParams.set("key", SMSLOCAL_API_KEY);
    url.searchParams.set("route", "1");
    url.searchParams.set("number", cleanNumber.length === 10 ? cleanNumber : rawPhone.replace(/\D/g, ""));
    url.searchParams.set("sms", message);

    if (SMSLOCAL_SENDER_ID) {
      url.searchParams.set("sender", SMSLOCAL_SENDER_ID);
    }
    if (SMSLOCAL_TEMPLATE_ID) {
      url.searchParams.set("templateid", SMSLOCAL_TEMPLATE_ID);
    }

    console.log("Dispatching to SMSLocal API...");
    const response = await fetch(url.toString(), { method: "GET" });
    const responseText = await response.text();
    console.log("SMSLocal response code/text:", responseText);

    // Common SMSLocal error codes:
    // 100: Success / Submitted
    // 102: Invalid Sender ID (requires DLT approved Sender ID)
    // 103: Low balance
    // 105: Invalid API Key
    return new Response(
      JSON.stringify({
        success: true,
        response: responseText,
        phone: rawPhone,
      }),
      {
        status: 200,
        headers: { "Content-Type": "application/json" },
      }
    );
  } catch (error: any) {
    console.error("Hook runtime error:", error);
    return new Response(
      JSON.stringify({ error: error.message }),
      { status: 500, headers: { "Content-Type": "application/json" } }
    );
  }
});
